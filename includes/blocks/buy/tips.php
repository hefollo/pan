<?php
/* 购买页底部的说明：会员等级怎么算、续费与升级、下载速度和流量跟着上传者走、附加包 */
if(!defined('IN_CRONLITE'))exit();
return [
	'name' => '购买说明',
	'group' => '购买页',
	'scope' => 'front',
	'pages' => ['buy'],
	'schema' => [
		['key'=>'text', 'type'=>'textarea', 'label'=>'说明', 'default'=>'买的是会员等级：有效期内按该等级的权限使用，到期后回到普通用户；同一个等级再买是续费，天数接在到期时间后面。
想换成更高的等级，限时会员用上面的「补差价升级」，只补到期前这段时间的差价，到期时间不变；升级后想延长时间，再买新等级的套餐。
「文件下载」的速度跟着上传的人走：你上传的文件，任何人下载都按你当前等级的速度，和下载的人是不是会员无关。
「分享流量」也跟着上传的人走：你的文件每月被下载、预览取走的总量，每月 1 日重新计算；用完后再扣分享流量包，都用完了别人就暂时下载不了你的文件。
「上传流量」是网站每月最多收你多少上传数据（没传完、失败的也算），用完后再扣上传流量包，都用完了就要等下个月才能再传。
加量包和在线编辑包是附加包，各有自己的到期时间，不影响会员到期时间；分享流量包、上传流量包永久有效，用完为止，两种不能互相抵扣。', 'help'=>'一行一段；清空不显示'],
	],
	'data' => function($cfg, &$ctx){
		$text = trim($cfg['text']);
		if($text === '')return ['tips_html'=>''];
		//行与行之间和原来模板里一样用 <br/> 加换行缩进
		$lines = array_map(function($l){ return htmlspecialchars(trim($l), ENT_QUOTES, 'UTF-8'); }, preg_split('/\r\n|\r|\n/', $text));
		return ['tips_html'=>implode("<br/>\n        ", $lines)];
	},
];
